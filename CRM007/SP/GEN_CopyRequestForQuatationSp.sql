           ,[cust_type]
           ,[curr_code]
           ,[decision_maker]
           ,[ship_addr]
           ,[issue_by]
           ,[issue_date]
           ,[submit_date]
           ,[ref_rev]
           ,[Uf_ERPP_SK_PaymentMethod]
           ,[Uf_ERPP_SK_TypeBusiness]
           ,[Uf_ERPP_PTTooling]
FROM [dbo].[ERPP_rfq] WHERE rfq_num = @RfqNum AND rfq_rev = @Revision

INSERT INTO [dbo].[ERPP_rfqitem]
           ([rfq_num]
           ,[rfq_rev]
