 
 
CREATE PROCEDURE [dbo].[GEN_CopyRequestForQuatationSp]
(
    @Infobar InfobarType OUTPUT
)
AS

SET XACT_ABORT ON;

DECLARE @NewRev tinyint,
    @Revision tinyint,
    @RfqNum nvarchar(15),
    @Severity INT = 0

EXEC @Severity = [dbo].[GetVariableSp] 'CopyRequestForQuatationSp.RfqNum', NULL, 0, @RfqNum OUTPUT, @Infobar OUTPUT;
EXEC @Severity = [dbo].[GetVariableSp] 'CopyRequestForQuatationSp.Revision', NULL, 0, @Revision OUTPUT, @Infobar OUTPUT;

SELECT @NewRev = max(rfq_rev) FROM ERPP_rfq 
WHERE rfq_num = @RfqNum

IF @NewRev IS NOT NULL AND @Revision <> @NewRev
BEGIN
	EXEC @Severity = dbo.MsgAppSp @Infobar OUTPUT, 'GEN_mERFQIsNotOriginal', @RfqNum, @Revision
	RETURN @Severity;
END

SET @NewRev = CASE WHEN @NewRev IS NULL THEN 0 ELSE @NewRev + 1 END

INSERT INTO [dbo].[ERPP_rfq]
           ([rfq_num]
           ,[rfq_rev]
           ,[rfq_source]
           ,[type]
           ,[plant]
           ,[sale_type]
           ,[status]
           ,[cust_num]
           ,[cust_seq]
           ,[cust_type]
           ,[curr_code]
           ,[decision_maker]
           ,[ship_addr]
